"""
Яблоки — калькулятор комплексных индексов зрелости.
Источник: отчёт «Разработка критериев оценки товарного качества... яблоки», этап 2,
раздел 3.3 (комплексные индексы степени зрелости).

Входные показатели:
  T    — твёрдость мякоти, кг/см²
  brix — содержание сухих растворимых веществ (СРВ), % Brix
  isi  — йодкрахмальная проба (ЙКП), баллы (шкала 1–10; для Штрайфа используется 1–5)
  acidity — титруемая кислотность, % (для индекса FARS; опционально)
"""

APPLE_VARIETIES = ["Айдаред", "Голден Делишес"]


def apple_indices(T, brix, isi, acidity=None):
    T = float(T); brix = float(brix); isi = float(isi)
    if T <= 0 or brix <= 0 or isi <= 0:
        raise ValueError("Твёрдость, Brix и ЙКП должны быть положительными")

    streif = T / (brix * isi)                    # индекс Штрайфа
    jaeger = T * (8 - isi) / brix                 # индекс Ягера
    mitin = brix * isi / T                        # индекс Митина
    fars = None
    if acidity not in (None, "", 0):
        fars = T * float(acidity) / (brix * isi)  # индекс FARS

    # Вердикт по йодкрахмальной пробе (правило из отчёта): ЙКП→1 = дозрел, реализовать.
    if isi <= 2:
        verdict = "Съёмная незрелость — крахмал высокий, длительное хранение"
    elif isi <= 4:
        verdict = "Оптимальный сбор для хранения (потребительская зрелость близко)"
    elif isi <= 6:
        verdict = "Потребительская зрелость — реализация"
    elif isi <= 8:
        verdict = "Зрелый, срочная реализация"
    else:
        verdict = "Перезревание — переработка/списание"

    return {
        "streif": round(streif, 4),
        "jaeger": round(jaeger, 4),
        "mitin": round(mitin, 4),
        "fars": round(fars, 4) if fars is not None else None,
        "verdict": verdict,
        "inputs": {"T": T, "brix": brix, "isi": isi, "acidity": acidity},
    }


