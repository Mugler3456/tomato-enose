# e-nose (МАГ-8): суммарный сигнал летучих по температурам (усл. ед.), V-образная динамика.
VOC_BY_TEMP = {
    8:  {"green": "10–22", "ripe": "20–22", "overripe": "15–16"},
    20: {"green": "10–22", "ripe": "≈50",   "overripe": "≈35"},
    27: {"green": "10–22", "ripe": "70–75", "overripe": "≈27"},
}

TEMPERATURES = [8, 12, 15, 20, 27]


def nearest_temp(t):
    return min(TEMPERATURES, key=lambda x: abs(x - t))


def ripening_stage_by_firmness(firmness):
    """Определить стадию дозревания по плотности мякоти (кг/см²)."""
    best = min(RIPENING_SCALE, key=lambda s: abs(s["firmness"] - firmness))
    return best


def avocado_lookup(temp, stage_idx=None, firmness=None):
    """Вернуть таблицу маркеров по температуре + текущую стадию."""
    t = nearest_temp(float(temp))
    block = TEMP_TABLE[t]
    result = {
        "temp": t,
        "opt_days": block["opt_days"],
        "exp_days": block["exp_days"],
        "markers": block["markers"],   # dict: marker -> (РЦ, магазин, критич)
        "voc": VOC_BY_TEMP.get(t),
        "scale": RIPENING_SCALE,
    }
    if firmness is not None:
        result["current_stage"] = ripening_stage_by_firmness(float(firmness))
    elif stage_idx is not None:
        result["current_stage"] = RIPENING_SCALE[int(stage_idx) - 1]
    return result
